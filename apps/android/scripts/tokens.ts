/** Generates the Compose design tokens from design/tokens.json, the one token source (the web
 * family generates its CSS from the same file). Run with `bun run tokens`; a test fails when the
 * committed output is stale. Nothing in the app hand-copies a token value. */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Scale = Record<string, number>;
interface Size {
  width: number;
  height: number;
}
interface TileSet {
  poster: Size;
  landscape: Size;
  square: Size;
  gap: number;
  pad: number;
  inset: number;
  peek: number;
  caption: number;
}
export interface Tokens {
  color: { dark: Record<string, string>; light: Record<string, string> };
  font: Record<string, string[]>;
  type: { tv: Scale; phone: Scale };
  space: Scale;
  radius: Scale;
  safeArea: { tv: Scale; phone: Scale };
  focus: { ring: number; halo: number; scaleCard: number; scaleTile: number };
  motion: { focusMs: number; panelMs: number; ease: string };
  tile: { tv: TileSet; phone: TileSet };
}

export const tokensPath = join(import.meta.dir, "../../../design/tokens.json");
export const kotlinPath = join(import.meta.dir, "../design/src/main/kotlin/app/marquee/design/Tokens.kt");
export const colorsPath = join(import.meta.dir, "../design/src/main/res/values/tokens_colors.xml");

const hex2 = (n: number) => n.toString(16).toUpperCase().padStart(2, "0");

/** `#RRGGBB` or `rgba(r, g, b, a)` to an ARGB integer, as 8 hex digits. */
export function argb(css: string): string {
  const plain = /^#([0-9a-fA-F]{6})$/.exec(css);
  if (plain) return `FF${(plain[1] as string).toUpperCase()}`;
  const rgba = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/.exec(css);
  if (rgba) {
    const [r, g, b] = [rgba[1], rgba[2], rgba[3]].map((v) => Number(v));
    const a = Math.round(Number(rgba[4]) * 255);
    return `${hex2(a)}${hex2(r as number)}${hex2(g as number)}${hex2(b as number)}`;
  }
  throw new Error(`unsupported color: ${css}`);
}

const num = (n: number) => `${n}`;
const dp = (n: number) => `${num(n)}.dp`;
const sp = (n: number) => `${num(n)}.sp`;
const float = (n: number) => `${num(n)}f`;

function dataClass(name: string, doc: string, fields: [string, string][]): string {
  const params = fields.map(([n, t]) => `    val ${n}: ${t},`).join("\n");
  return `/** ${doc} */\n@Immutable\ndata class ${name}(\n${params}\n)\n`;
}

function instance(type: string, entries: [string, string][]): string {
  return `${type}(\n${entries.map(([k, v]) => `            ${k} = ${v},`).join("\n")}\n        )`;
}

function tileSet(t: TileSet): string {
  const size = (s: Size) => `TileSize(${dp(s.width)}, ${dp(s.height)})`;
  return instance("TileMetrics", [
    ["poster", size(t.poster)],
    ["landscape", size(t.landscape)],
    ["square", size(t.square)],
    ["gap", dp(t.gap)],
    ["pad", dp(t.pad)],
    ["inset", dp(t.inset)],
    ["peek", dp(t.peek)],
    ["caption", dp(t.caption)],
  ]);
}

export function generate(t: Tokens): string {
  const colorKeys = Object.keys(t.color.dark);
  const typeKeys = Object.keys(t.type.tv);
  const spaceKeys = Object.keys(t.space);
  const radiusKeys = Object.keys(t.radius);
  const palette = (c: Record<string, string>) =>
    instance(
      "Palette",
      colorKeys.map((k) => [k, `Color(0x${argb(c[k] as string)})`]),
    );
  const typeScale = (s: Scale) =>
    instance(
      "TypeScale",
      typeKeys.map((k) => [k, sp(s[k] as number)]),
    );
  const insets = (s: Scale) =>
    instance("Insets", [
      ["top", dp(s.top as number)],
      ["bottom", dp(s.bottom as number)],
      ["side", dp(s.side as number)],
    ]);
  const [x1, y1, x2, y2] = (/cubic-bezier\(([^)]+)\)/.exec(t.motion.ease)?.[1] ?? "").split(",").map((v) => Number(v));
  if ([x1, y1, x2, y2].some((v) => v === undefined || Number.isNaN(v))) throw new Error(`unsupported easing: ${t.motion.ease}`);
  const families = Object.entries(t.font).map(([role, stack]) => `        val ${role} = listOf(${stack.map((f) => `"${f}"`).join(", ")})`);

  return [
    "// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.",
    "package app.marquee.design",
    "",
    "import androidx.compose.animation.core.CubicBezierEasing",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.Dp",
    "import androidx.compose.ui.unit.TextUnit",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
    dataClass("Palette", "One color set; the dark one is the TV default.", colorKeys.map((k) => [k, "Color"])),
    dataClass("TypeScale", "Text sizes: TV points on the 1920x1080 canvas, or phone sp.", typeKeys.map((k) => [k, "TextUnit"])),
    dataClass("Spacing", "Spacing steps.", spaceKeys.map((k) => [k, "Dp"])),
    dataClass("Radii", "Corner radii.", radiusKeys.map((k) => [k, "Dp"])),
    dataClass("Insets", "Safe area insets.", [
      ["top", "Dp"],
      ["bottom", "Dp"],
      ["side", "Dp"],
    ]),
    dataClass("TileSize", "Width and height of one tile shape.", [
      ["width", "Dp"],
      ["height", "Dp"],
    ]),
    dataClass("TileMetrics", "Tile shapes and row layout (the web's row metrics).", [
      ["poster", "TileSize"],
      ["landscape", "TileSize"],
      ["square", "TileSize"],
      ["gap", "Dp"],
      ["pad", "Dp"],
      ["inset", "Dp"],
      ["peek", "Dp"],
      ["caption", "Dp"],
    ]),
    "object Tokens {",
    `    val dark = ${palette(t.color.dark)}`,
    "",
    `    val light = ${palette(t.color.light)}`,
    "",
    `    val tvType = ${typeScale(t.type.tv)}`,
    "",
    `    val phoneType = ${typeScale(t.type.phone)}`,
    "",
    `    val space = ${instance("Spacing", spaceKeys.map((k) => [k, dp(t.space[k] as number)]))}`,
    "",
    `    val radius = ${instance("Radii", radiusKeys.map((k) => [k, dp(t.radius[k] as number)]))}`,
    "",
    `    val tvSafe = ${insets(t.safeArea.tv)}`,
    "",
    `    val phoneSafe = ${insets(t.safeArea.phone)}`,
    "",
    `    val tvTiles = ${tileSet(t.tile.tv)}`,
    "",
    `    val phoneTiles = ${tileSet(t.tile.phone)}`,
    "",
    `    val focusRing = ${dp(t.focus.ring)}`,
    `    val focusHalo = ${dp(t.focus.halo)}`,
    `    const val FOCUS_SCALE_CARD = ${float(t.focus.scaleCard)}`,
    `    const val FOCUS_SCALE_TILE = ${float(t.focus.scaleTile)}`,
    "",
    `    const val FOCUS_MS = ${t.motion.focusMs}`,
    `    const val PANEL_MS = ${t.motion.panelMs}`,
    `    val ease = CubicBezierEasing(${float(x1 as number)}, ${float(y1 as number)}, ${float(x2 as number)}, ${float(y2 as number)})`,
    "",
    "    object Fonts {",
    families.join("\n"),
    "    }",
    "}",
    "",
  ]
    .join("\n");
}

/** Window background colors for the theme that shows before the first frame. */
export function colors(t: Tokens): string {
  const line = (name: string, css: string) => `    <color name="${name}">#${argb(css)}</color>`;
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by scripts/tokens.ts from design/tokens.json. Do not edit. -->",
    "<resources>",
    line("marquee_bg_dark", t.color.dark.bg as string),
    line("marquee_bg_light", t.color.light.bg as string),
    line("marquee_accent", t.color.dark.accent as string),
    "</resources>",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const tokens = JSON.parse(readFileSync(tokensPath, "utf8")) as Tokens;
  writeFileSync(kotlinPath, generate(tokens));
  writeFileSync(colorsPath, colors(tokens));
  console.log(`wrote ${kotlinPath} and ${colorsPath}`);
}
