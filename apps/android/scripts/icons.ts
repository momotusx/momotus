type Attrs = Record<string, string | number>;
type Node = [string, Attrs];

const n = (v: string | number | undefined, fallback = 0) => (v === undefined ? fallback : Number(v));
const f = (x: number) => `${Math.round(x * 1000) / 1000}`;

function arcCircle(cx: number, cy: number, rx: number, ry: number): string {
  return `M${f(cx - rx)} ${f(cy)}a${f(rx)} ${f(ry)} 0 1 0 ${f(2 * rx)} 0a${f(rx)} ${f(ry)} 0 1 0 ${f(-2 * rx)} 0z`;
}

function rect(a: Attrs): string {
  const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
  const rx = Math.min(n(a.rx, n(a.ry)), w / 2);
  const ry = Math.min(n(a.ry, rx), h / 2);
  if (rx === 0 && ry === 0) return `M${f(x)} ${f(y)}h${f(w)}v${f(h)}h${f(-w)}z`;
  return (
    `M${f(x + rx)} ${f(y)}h${f(w - 2 * rx)}a${f(rx)} ${f(ry)} 0 0 1 ${f(rx)} ${f(ry)}v${f(h - 2 * ry)}` +
    `a${f(rx)} ${f(ry)} 0 0 1 ${f(-rx)} ${f(ry)}h${f(-(w - 2 * rx))}a${f(rx)} ${f(ry)} 0 0 1 ${f(-rx)} ${f(-ry)}` +
    `v${f(-(h - 2 * ry))}a${f(rx)} ${f(ry)} 0 0 1 ${f(rx)} ${f(-ry)}z`
  );
}

function pathOf([tag, a]: Node): string {
  switch (tag) {
    case "path":
      return String(a.d);
    case "circle":
      return arcCircle(n(a.cx), n(a.cy), n(a.r), n(a.r));
    case "ellipse":
      return arcCircle(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
    case "rect":
      return rect(a);
    case "line":
      return `M${f(n(a.x1))} ${f(n(a.y1))}L${f(n(a.x2))} ${f(n(a.y2))}`;
    case "polyline":
    case "polygon": {
      const points = String(a.points).trim().split(/[\s,]+/).map(Number);
      const pairs: string[] = [];
      for (let i = 0; i + 1 < points.length; i += 2) pairs.push(`${f(points[i] as number)} ${f(points[i + 1] as number)}`);
      return `M${pairs.join("L")}${tag === "polygon" ? "z" : ""}`;
    }
    default:
      throw new Error(`unsupported SVG element <${tag}>`);
  }
}

const pascal = (name: string) =>
  name
    .split("-")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");

export function generate(nodes: Record<string, Node[]>): string {
  const body = ICONS.map((name) => {
    const parts = nodes[name];
    if (!parts) throw new Error(`no Lucide icon named ${name}`);
    const paths = parts.map((p) => `        "${pathOf(p)}",`).join("\n");
    return `    val ${pascal(name)}: ImageVector by lazy {\n        strokeIcon(\n            "${name}",\n${paths}\n        )\n    }`;
  });
  return [
    "// Generated by scripts/icons.ts from Lucide (lucide-static, ISC). Do not edit.",
    "package app.marquee.design",
    "",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "",
    "/** The one outline icon set (Lucide), always shown with a text label. */",
    "object Icons {",
    body.join("\n\n"),
    "}",
    "",
  ].join("\n");
}

export const readNodes = () => JSON.parse(readFileSync(nodesPath, "utf8")) as Record<string, Node[]>;

if (import.meta.main) {
  writeFileSync(iconsPath, generate(readNodes()));
  console.log(`wrote ${iconsPath}`);
}
