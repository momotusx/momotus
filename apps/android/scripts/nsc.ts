/** Generates the app's network security config.
 *
 * Cleartext is denied except for the loopback stream server (127.0.0.1) and the
 * CA revocation hosts that the vendored rustls-platform-verifier component lists
 * in its own config: the library's certificate revocation fetches use plain HTTP
 * and soft-fail, so blocking them would silently turn revocation checking off.
 * The AAR's config is replaced in the manifest (`tools:replace`), so this file
 * carries its host list. Run with `bun run nsc`; a test fails when stale. */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

export const aarPath = join(
  import.meta.dir,
  "../vendor/maven/org/rustls/rustls-platform-verifier/0.2.0/rustls-platform-verifier-0.2.0.aar",
);
export const xmlPath = join(import.meta.dir, "../app/src/main/res/xml/network_security_config.xml");

export function verifierHosts(aar: string): string[] {
  const out = Bun.spawnSync(["unzip", "-p", aar, "res/xml/network_security_config.xml"]);
  if (out.exitCode !== 0) throw new Error(`cannot read the verifier network config from ${aar}`);
  const xml = out.stdout.toString();
  return [...xml.matchAll(/<domain includeSubdomains="true">([^<]+)<\/domain>/g)].map((m) => m[1] as string);
}

export function generate(hosts: string[]): string {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by scripts/nsc.ts. Do not edit. -->",
    "<network-security-config>",
    '    <base-config cleartextTrafficPermitted="false" />',
    '    <domain-config cleartextTrafficPermitted="true">',
    '        <domain includeSubdomains="false">127.0.0.1</domain>',
    ...hosts.map((h) => `        <domain includeSubdomains="true">${h}</domain>`),
    "    </domain-config>",
    "</network-security-config>",
    "",
  ];
  return lines.join("\n");
}

if (import.meta.main) {
  writeFileSync(xmlPath, generate(verifierHosts(aarPath)));
  console.log(`wrote ${xmlPath}`);
}
